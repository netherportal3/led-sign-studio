"""Hand-drawn bitmap fonts for the LED panel.

Each glyph is a list of row strings, '#' = lit. Glyphs are proportional (their own width) and are
spaced 1 px apart. Rows count from the top of the cell.

Pixel 5x7: capitals and digits use rows 0-6 (baseline row 6). Row 7 holds descenders (g j p q y , ;).
Tiny 3x5: rows 0-4, capitals only (lowercase is drawn as capitals), so two lines fit in 16 rows.
"""
from __future__ import annotations

from dataclasses import dataclass, field


@dataclass
class PixelFont:
    id: str
    label: str
    cell_height: int      # rows per line including descender rows
    cap_top: int          # first row of a capital letter
    baseline: int         # last row of a capital letter
    line_gap: int         # blank rows between stacked lines
    space: int            # width of ' '
    uppercase_only: bool
    glyphs: dict[str, list[str]] = field(default_factory=dict)

    def glyph(self, ch: str) -> list[str]:
        if ch == " ":
            return ["." * self.space]
        if self.uppercase_only:
            ch = ch.upper()
        g = self.glyphs.get(ch)
        if g is None:
            ch = FALLBACKS.get(ch, "?")
            if self.uppercase_only:
                ch = ch.upper()
            g = self.glyphs.get(ch) or self.glyphs["?"]
        return g


# Characters people type that the fonts do not draw, mapped to ones they do.
FALLBACKS = {
    "‘": "'", "’": "'", "“": '"', "”": '"', "–": "-", "—": "-",
    "…": ".", " ": " ", "\t": " ", "❤": "♥", "×": "x", "·": ".",
}


def _g(*rows: str) -> list[str]:
    w = max(len(r) for r in rows)
    assert all(len(r) == w for r in rows), rows
    return list(rows)


